from playwright.sync_api import sync_playwright
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 page=browser.new_page(timezone_id="America/Los_Angeles",viewport={"width":1440,"height":1000})
 page.on('pageerror',lambda e:print(str(e)))
 page.goto('http://127.0.0.1:5189/test/home-metric.html')
 page.get_by_text('隔离测试指标',exact=True).wait_for(timeout=60000)
 page.get_by_role('button',name='编辑',exact=True).click()
 assert page.locator('input').evaluate_all("els => els.some(e => e.value === '2026-10-01 00:00:00')")
 page.get_by_text('北京时间开始：2026-10-01 00:00:00').wait_for()
 page.get_by_text('北京时间结束：2026-11-01 00:00:00').wait_for()
 assert page.get_by_text('截至当前时刻',exact=True).count()==0
 page.get_by_role('button',name='按本人权限预览').click()
 page.get_by_text('当前本人权限下结果：7').wait_for()
 page.wait_for_timeout(400)
 page.screenshot(path='test/home-metric-admin.png',full_page=True)
 page.set_viewport_size({'width':390,'height':900})
 page.get_by_text('北京时间开始：2026-10-01 00:00:00').scroll_into_view_if_needed()
 page.screenshot(path='test/home-metric-admin-mobile.png',full_page=True)
 page.evaluate('window.failSave=true')
 page.get_by_role('button',name='保存草稿').click()
 page.get_by_text('配置已被其他人修改，请重新打开').first.wait_for()
 page.get_by_role('button',name='保存草稿').click()
 assert page.get_by_role('dialog',name='指标配置').is_visible()
 page.get_by_role('button',name='取消',exact=True).click()
 page.get_by_role('button',name='编辑',exact=True).click()
 page.get_by_role('button',name='保存草稿').click()
 page.get_by_role('button',name='发布',exact=True).click()
 page.get_by_text('已发布',exact=True).wait_for()
 browser.close()
 print('Admin edit/preview/save/publish passed')


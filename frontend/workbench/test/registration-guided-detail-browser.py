# -*- coding: utf-8 -*-
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
URL = 'http://127.0.0.1:5174/test/registration-guided-detail.html'
OUT = Path('frontend/workbench/tmp')
with sync_playwright() as p:
    browser = p.chromium.launch(channel='chrome', headless=True)
    errors = []
    page = browser.new_page(viewport={'width':1440,'height':960})
    page.on('pageerror', lambda error: errors.append(str(error)))
    def open_state(state=''):
        page.goto(URL + '?state=' + state)
        if state in ('completed','ended','cancelled'): page.get_by_role('tab',name='全部',exact=True).click()
        expect(page.locator('.registration-detail')).to_be_visible()
    def complete():
        return page.get_by_role('button', name='完成报名履约', exact=True)
    def select_wait():
        page.locator('.registration-route-row .ant-select').first.click()
        page.get_by_title('待分班',exact=True).click()
    for width in (1920,1440,1280,390):
        page.set_viewport_size({'width':width,'height':960})
        page.goto(URL+'?state=long')
        expect(page.locator('.lead-inbox-item')).to_have_count(2)
        if width == 390: page.locator('.lead-inbox-item').first.click()
        expect(page.locator('.registration-detail')).to_be_visible()
        expect(complete()).to_be_disabled()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        info=page.locator('.registration-information').bounding_box()
        ops=page.locator('.registration-operation-scroll').bounding_box()
        if width > 1000: assert ops['x'] > info['x'] + info['width'] - 2
        else: assert abs(ops['x']-info['x']) < 2
        footer=page.locator('.registration-detail-actions').bounding_box()
        assert footer['y']+footer['height'] <= 960
        if width > 1000:
            page.locator('.registration-operation-scroll').evaluate('(e)=>e.scrollTop=e.scrollHeight')
            assert page.locator('.registration-information').evaluate('(e)=>e.scrollTop') == 0
            assert page.locator('.registration-detail-actions').bounding_box()['y'] == footer['y']
            page.locator('.registration-operation-scroll').evaluate('(e)=>e.scrollTop=0')
        page.screenshot(path=str(OUT/f'registration-guided-{width}.png'),full_page=True)
        if width == 390:
            page.get_by_role('button',name='返回列表').click()
            expect(page.locator('.lead-inbox-item').first).to_be_visible()
    page.set_viewport_size({'width':1440,'height':960})
    open_state()
    select_wait()
    page.locator('.lead-inbox-item').nth(1).click()
    expect(page.get_by_role('dialog')).to_contain_text('分班选择尚未保存')
    page.get_by_role('button',name='继续编辑').click()
    expect(page.locator('.registration-detail-hero')).to_contain_text('验收学员1')
    page.locator('.lead-inbox-item').nth(1).click()
    page.get_by_role('button',name='放弃修改').click()
    expect(page.locator('.registration-detail-hero')).to_contain_text('验收学员2')
    open_state()
    page.get_by_role('button',name='保存分班',exact=True).click()
    expect(page.locator('.registration-information')).to_contain_text('当前交付班级')
    expect(page.get_by_role('button',name='保存分班',exact=True)).to_have_count(0)
    expect(complete()).to_be_disabled()
    assert not page.evaluate('window.registrationRows[1].deliveryEstablished')
    open_state('ready')
    expect(complete()).to_be_enabled()
    complete().click()
    expect(page.locator('.lead-inbox-item')).to_have_count(1)
    open_state('denied')
    expect(page.get_by_role('checkbox',name='报名资料确认')).to_be_disabled()
    expect(complete()).to_be_disabled()
    expect(page.get_by_role('button',name='保存分班',exact=True)).to_have_count(0)
    for state in ('completed','ended','cancelled'):
        open_state(state)
        expect(complete()).to_have_count(0)
        expect(page.get_by_role('checkbox',name='报名资料确认')).to_be_disabled()
        expect(page.locator('.registration-information')).to_contain_text('办理结果')
    open_state('item-error')
    check=page.get_by_role('checkbox',name='报名资料确认')
    check.click()
    expect(page.get_by_text('清单保存失败，请重试',exact=True)).to_be_visible()
    expect(check).not_to_be_checked()
    check.click()
    expect(check).to_be_checked()
    expect(page.locator('.registration-checklist-progress')).to_contain_text('人工确认 1 / 1')
    for state in ('slow-item','slow-save'):
        open_state(state)
        if state == 'slow-item': page.get_by_role('checkbox',name='报名资料确认').click()
        else: page.get_by_role('button',name='保存分班',exact=True).click()
        expect(complete()).to_be_disabled()
        page.locator('.lead-inbox-item').nth(1).click()
        expect(page.locator('.registration-detail-hero')).to_contain_text('验收学员2')
        page.wait_for_timeout(900)
        expect(page.locator('.registration-detail-hero')).to_contain_text('验收学员2')
        expect(page.get_by_role('checkbox',name='报名资料确认')).not_to_be_checked()
    open_state()
    page.locator('input[type=file]').set_input_files({'name':'proof.png','mimeType':'image/png','buffer':b'fixture'})
    expect(page.locator('.registration-checklist-progress')).to_contain_text('必传附件 1 / 1')
    expect(page.get_by_alt_text('proof.png')).to_be_visible()
    page.get_by_role('button',name='删除 proof.png').click()
    expect(page.locator('.registration-checklist-progress')).to_contain_text('必传附件 0 / 1')
    page.get_by_role('button',name='结束本产品（无需交付）',exact=True).click()
    page.get_by_role('button',name='确认结束',exact=True).click()
    expect(page.get_by_text('请填写关闭原因',exact=True)).to_be_visible()
    page.get_by_role('textbox',name='结束原因').fill('无需交付')
    page.get_by_role('button',name='确认结束',exact=True).click()
    expect(page.get_by_role('dialog')).to_have_count(0)
    open_state('legacy')
    page.get_by_role('checkbox',name='测试部门').check()
    page.locator('.registration-route-row .ant-select').click()
    page.get_by_title('测试规划师',exact=True).click()
    expect(page.locator('.registration-step').first).to_contain_text('已建立交付')
    page.goto(URL+'?state=detail-error')
    expect(page.get_by_text('详情加载失败，请重试',exact=True)).to_be_visible()
    page.locator('.registration-detail-pane').get_by_role('button').filter(has_text='重试').click()
    expect(page.locator('.registration-detail')).to_be_visible()
    open_state()
    select_wait()
    page.get_by_role('button',name='刷新',exact=False).click()
    page.get_by_role('button',name='放弃修改').click()
    expect(page.locator('.registration-route-row')).to_contain_text('首次班级')
    page.goto(URL+'?state=slow-detail')
    expect(page.locator('.lead-inbox-item')).to_have_count(2)
    page.locator('.lead-inbox-item').nth(1).click()
    expect(page.locator('.registration-detail-hero')).to_contain_text('验收学员2')
    page.wait_for_timeout(800)
    expect(page.locator('.registration-detail-hero')).to_contain_text('验收学员2')
    open_state('unassigned')
    select_wait()
    page.get_by_role('button',name='保存分班',exact=True).click()
    expect(page.locator('.registration-information')).to_contain_text('当前交付班级')
    open_state('error')
    page.get_by_role('button',name='保存分班',exact=True).click()
    expect(page.get_by_text('保存分班失败，请重试',exact=True)).to_be_visible()
    page.set_viewport_size({'width':1000,'height':960})
    open_state('long')
    info=page.locator('.registration-information').bounding_box()
    ops=page.locator('.registration-operation-scroll').bounding_box()
    assert abs(info['x']-ops['x'])<2
    assert page.locator('.registration-detail-actions').bounding_box()['y']<960
    assert not errors, errors
    browser.close()
print('PASS: four widths, independent scroll/footer, draft guard, finance/save/complete, permissions, terminal states, failed item retry, stale mutations, attachments, close, legacy, detail retry')

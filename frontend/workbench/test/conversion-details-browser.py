# UTF-8. Real Chromium against isolated synthetic API fixtures, not authenticated runtime acceptance.
from pathlib import Path
import re
from playwright.sync_api import sync_playwright, expect

OUT = Path('D:/ZSJ-OS-backups/conversion-details-browser')
OUT.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(channel='chrome', headless=True)
    page = browser.new_page(viewport={'width': 1600, 'height': 1000})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:5174/test/conversion-details.html')
    def open_conversion():
        page.locator('.performance-panel').filter(has=page.get_by_text('多周期成交率', exact=True)).locator('button').click()
        expect(page.get_by_text('筛选结果 48 位客资', exact=False)).to_be_visible()
    open_conversion()
    drawer = page.get_by_role('dialog')
    expect(drawer.get_by_text('50.00% · 成交客资 24 / 口径客资 48', exact=True)).to_be_visible()
    page.get_by_role('combobox', name='成交状态', exact=True).click()
    page.get_by_title('已成交 (24)', exact=True).click()
    expect(page.get_by_text('筛选结果 24 位客资', exact=False)).to_be_visible()
    for label, option in [('统计归类', '期间新接 (48)'), ('客资分类', '分类快照甲 (48)'), ('来源渠道', '渠道快照甲 (48)'), ('订单商品', '商品快照甲 (24)')]:
        page.get_by_role('combobox', name=label, exact=True).click()
        page.get_by_title(option, exact=True).click()
    params = page.evaluate("window.conversionFixture.requests.filter(r => r.url.endsWith('/conversion-details')).at(-1).params")
    assert params['conversionStatus'] == 'converted' and params['populationKind'] == 'current'
    assert params['categoryKey'] == 'cat' and params['channelKey'] == 'channel' and params['productKey'] == 'product'
    expect(page.get_by_text('筛选结果 24 位客资', exact=False)).to_be_visible()
    page.get_by_title('2', exact=True).click()
    expect(page.get_by_text('KZ-41', exact=True)).to_be_visible()
    row = page.locator('tr').filter(has=page.get_by_text('KZ-41', exact=True))
    row.get_by_role('button', name='订单详情').click()
    expect(page.get_by_text('订单概览', exact=True)).to_be_visible()
    expect(page.get_by_role('dialog')).to_have_count(1)
    assert page.url.endswith('/test/conversion-details.html')
    expect(page.get_by_role('button', name='终止审批', exact=True)).to_have_count(0)
    page.screenshot(path=str(OUT/'order-desktop.png'))
    page.get_by_role('button', name='返回明细列表').click()
    page.evaluate("window.conversionFixture.mode('order-error')")
    row.get_by_role('button', name='订单详情').click()
    expect(page.get_by_text('无权查询该订单', exact=True)).to_be_visible()
    page.evaluate("window.conversionFixture.mode('ok')")
    page.get_by_role('button', name=re.compile(r'重\s*试')).click()
    expect(page.get_by_text('订单概览', exact=True)).to_be_visible()
    page.get_by_role('button', name='返回明细列表').click()
    expect(page.get_by_text('KZ-41', exact=True)).to_be_visible()
    expect(page.locator('.ant-pagination-item-active')).to_have_attribute('title', '2')
    row.get_by_role('button', name='客资详情').click()
    expect(page.get_by_text('验证客资', exact=True)).to_be_visible()
    page.get_by_role('tab', name='申诉记录', exact=True).click()
    expect(page.get_by_text('暂无申诉记录', exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='发起第 1 次申诉')).to_have_count(0)
    page.get_by_role('button', name='返回明细列表').click()
    page.get_by_role('button', name='重置筛选').click()
    expect(page.get_by_text('筛选结果 48 位客资', exact=False)).to_be_visible()
    expect(page.locator('.ant-pagination-item-active')).to_have_attribute('title', '1')
    # Preserving the list DOM also preserves both vertical and horizontal scroll positions.
    list_panel = page.get_by_role('button', name='重置筛选').locator('xpath=../../..')
    list_panel.evaluate('(element) => element.scrollTop = 350')
    page.locator('tr').filter(has=page.get_by_text('KZ-9', exact=True)).get_by_role('button', name='客资详情').scroll_into_view_if_needed()
    top = list_panel.evaluate('(element) => element.scrollTop')
    assert top > 0
    expect(page.locator('tr').filter(has=page.get_by_text('KZ-9', exact=True))).to_have_count(1)
    page.locator('tr').filter(has=page.get_by_text('KZ-9', exact=True)).get_by_role('button', name='客资详情').click()
    expect(page.get_by_text('验证客资', exact=True)).to_be_visible()
    page.get_by_role('button', name='返回明细列表').click()
    assert abs(list_panel.evaluate('(element) => element.scrollTop') - top) <= 2
    search = page.get_by_label('客资或订单编号', exact=True)
    search.fill('KZ-NONE'); search.press('Enter')
    expect(page.get_by_text('没有符合筛选条件的客资', exact=True)).to_be_visible()
    expect(drawer.get_by_text('50.00% · 成交客资 24 / 口径客资 48', exact=True)).to_be_visible()
    page.evaluate("window.conversionFixture.mode('error')")
    page.get_by_role('button', name='重置筛选').click()
    expect(page.get_by_text('模拟明细网络失败', exact=True)).to_be_visible()
    page.evaluate("window.conversionFixture.mode('ok')")
    page.get_by_role('button', name=re.compile(r'重\s*试')).click()
    expect(page.get_by_text('KZ-1', exact=True)).to_be_visible()
    page.screenshot(path=str(OUT/'list-desktop.png'))
    page.evaluate('window.conversionFixture.navigate()')
    expect(page.get_by_role('heading', name='其他页面')).to_be_visible()
    expect(page.locator('.ant-drawer-mask:visible')).to_have_count(0)
    page.evaluate('window.conversionFixture.back()')
    expect(page.locator('.ant-drawer-mask:visible')).to_have_count(0)
    open_conversion()
    page.set_viewport_size({'width': 390, 'height': 844})
    expect(drawer).to_be_visible()
    page.wait_for_function("document.querySelector('[role=dialog]').getBoundingClientRect().width <= 390")
    assert drawer.bounding_box()['width'] <= 390
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(OUT/'list-mobile.png'))
    page.locator('tr').filter(has=page.get_by_text('KZ-1', exact=True)).get_by_role('button', name='订单详情').click()
    expect(page.get_by_text('订单概览', exact=True)).to_be_visible()
    page.screenshot(path=str(OUT/'order-mobile.png'))
    page.evaluate('window.conversionFixture.navigate()')
    expect(page.locator('.ant-drawer-mask:visible')).to_have_count(0)
    page.evaluate('window.conversionFixture.back()')
    page.evaluate('window.conversionFixture.revokeDetails()')
    open_conversion()
    expect(page.get_by_role('button', name='客资详情', exact=True)).to_have_count(0)
    expect(page.get_by_role('button', name='订单详情', exact=True)).to_have_count(0)
    page.get_by_role('button', name='关闭', exact=True).click()
    page.evaluate("window.conversionFixture.mode('denied')")
    page.locator('.performance-panel').filter(has=page.get_by_text('多周期成交率', exact=True)).locator('button').click()
    expect(page.get_by_text('无权查看该业绩范围', exact=True).last).to_be_visible()
    expect(page.get_by_text('KZ-1', exact=True)).to_have_count(0)
    page.evaluate("window.conversionFixture.mode('ok')")
    page.evaluate('window.conversionFixture.navigate()')
    expect(page.locator('.ant-drawer-mask:visible')).to_have_count(0)
    page.evaluate('window.conversionFixture.back()')
    page.locator('.performance-heading button').click()
    page.locator('.performance-panel').filter(has=page.get_by_text('多周期业绩', exact=True)).locator('button').click()
    expect(page.get_by_text('DD-100', exact=True)).to_be_visible()
    page.evaluate('window.conversionFixture.navigate()')
    expect(page.locator('.ant-drawer-mask:visible')).to_have_count(0)
    assert not errors, errors
    print('PASS: filters, pagination, fixed ratio, same-drawer readonly order/lead, scroll restoration, retry, permissions, retained-route cleanup, desktop/mobile')
    browser.close()

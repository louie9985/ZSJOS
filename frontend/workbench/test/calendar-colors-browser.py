# -*- coding: utf-8 -*-
import tempfile,os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
BASE=os.environ.get('WORKBENCH_TEST_URL','http://127.0.0.1:5174')
OUT=Path(tempfile.mkdtemp(prefix='calendar-colors-'))
with sync_playwright() as p:
 browser=p.chromium.launch(channel='chrome',headless=True)
 for width in [390,1440]:
  for dark in [False,True]:
   context=browser.new_context(viewport={'width':width,'height':1000})
   context.add_init_script("localStorage.setItem('crm-theme', JSON.stringify({preset:'"+('default-dark' if dark else 'default-light')+"'}))")
   page=context.new_page()
   page.goto(BASE+'/test/calendar-colors.html?scene=course')
   page.get_by_role('button',name='新增课程').click()
   editor=page.get_by_role('dialog',name='新增课程安排')
   editor.get_by_role('button',name='公共营养师',exact=True).click()
   expect(editor.locator('.calendar-color-preview')).to_have_css('background-color','rgb(106, 191, 109)')
   editor.get_by_role('button',name='保存为快捷色',exact=True).click()
   dialog=page.get_by_role('dialog',name='保存为快捷色',exact=True)
   dialog.get_by_label('快捷色名称').fill('内部培训')
   dialog.locator('.ant-modal-footer .ant-btn-primary').click()
   expect(editor.get_by_role('button',name='内部培训',exact=True)).to_be_visible()
   editor.get_by_label('课程名称',exact=True).fill('颜色验收课程')
   editor.get_by_label('课程形式',exact=True).click()
   page.get_by_title('直播',exact=True).click()
   editor.locator('.ant-modal-footer .ant-btn-primary').click()
   expect(editor).not_to_be_visible()
   expect(page.locator('.course-calendar-summary').first).to_have_css('background-color','rgb(106, 191, 109)')
   page.reload()
   expect(page.locator('.course-calendar-summary').first).to_have_css('background-color','rgb(106, 191, 109)')
   page.locator('.course-calendar-summary').first.click()
   page.locator('.course-calendar-timeline-card').get_by_label('编辑课程',exact=True).click()
   editor=page.get_by_role('dialog',name='编辑课程安排')
   expect(editor.get_by_role('button',name='内部培训',exact=True)).to_be_visible()
   editor.get_by_role('button',name='管理快捷色',exact=True).click()
   manage=page.get_by_role('dialog',name='管理快捷色',exact=True)
   manage.locator('.calendar-color-manage-row button').last.click()
   page.locator('.ant-popconfirm .ant-btn-primary').click()
   expect(manage.get_by_text('暂无快捷色')).to_be_visible()
   manage.locator('.ant-modal-close').click()
   expect(editor.locator('.calendar-color-preview')).to_have_css('background-color','rgb(106, 191, 109)')
   editor.get_by_role('button',name='恢复默认底色',exact=True).click()
   editor.locator('.ant-modal-footer .ant-btn-primary').click()
   expect(page.locator('.course-calendar-summary').first).to_have_attribute('data-calendar-colored','false')
   page.screenshot(path=str(OUT/f'course-{width}-{dark}.png'),full_page=True)
   page.evaluate("""sessionStorage.setItem('palette-PERSONAL', JSON.stringify({presets:[],colors:[{id:'personal-test',name:'内部会议',color:'#112233'}]}))""")
   page.goto(BASE+'/test/calendar-colors.html?scene=personal')
   page.get_by_role('button',name='新建日程').click()
   personal=page.get_by_role('dialog',name='新建日程')
   personal.get_by_role('button',name='内部会议',exact=True).click()
   personal.get_by_label('标题',exact=True).fill('个人颜色验收')
   personal.locator('.ant-modal-footer .ant-btn-primary').click()
   expect(personal).not_to_be_visible()
   page.reload()
   expect(page.locator('.personal-calendar-event').first).to_have_css('background-color','rgb(17, 34, 51)')
   page.goto(BASE+'/test/calendar-colors.html?scene=personal&denied=1')
   page.get_by_role('button',name='新建日程').click()
   editor=page.get_by_role('dialog',name='新建日程')
   expect(editor.get_by_role('button',name='保存为快捷色',exact=True)).to_have_count(0)
   expect(editor.get_by_label('自选颜色')).to_be_visible()
   expect(editor.get_by_role('button',name='公共营养师',exact=True)).to_have_count(0)
   page.wait_for_timeout(400)
   page.screenshot(path=str(OUT/f'personal-{width}-{dark}.png'),full_page=True)
   page.goto(BASE+'/test/calendar-colors.html?scene=course&error=1')
   page.get_by_role('button',name='新增课程').click()
   retry=page.get_by_role('dialog',name='新增课程安排')
   expect(retry.get_by_text('颜色加载失败',exact=True)).to_be_visible()
   expect(retry.get_by_label('自选颜色')).to_be_visible()
   retry.locator('.ant-alert button').click()
   expect(retry.get_by_role('button',name='公共营养师',exact=True)).to_be_visible()
   page.goto(BASE+'/test/calendar-colors.html?scene=course&save-error=1')
   page.get_by_role('button',name='新增课程').click()
   retry=page.get_by_role('dialog',name='新增课程安排')
   retry.get_by_role('button',name='公共营养师',exact=True).click()
   retry.get_by_role('button',name='保存为快捷色',exact=True).click()
   save_dialog=page.get_by_role('dialog',name='保存为快捷色',exact=True)
   save_dialog.get_by_label('快捷色名称').fill('重试保留名称')
   save_dialog.locator('.ant-modal-footer .ant-btn-primary').click()
   expect(save_dialog.get_by_text('快捷色保存失败，请重试',exact=True)).to_be_visible()
   expect(save_dialog.get_by_label('快捷色名称')).to_have_value('重试保留名称')
   save_dialog.locator('.ant-modal-footer .ant-btn-primary').click()
   expect(save_dialog).not_to_be_visible()
   expect(retry.get_by_role('button',name='重试保留名称',exact=True)).to_be_visible()
   print('PASS',width,'dark',dark,flush=True)
   context.close()
 browser.close()
print('Screenshots:',OUT)

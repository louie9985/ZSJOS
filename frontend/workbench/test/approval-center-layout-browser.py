# -*- coding: utf-8 -*-
from pathlib import Path
from tempfile import gettempdir
from playwright.sync_api import sync_playwright, expect

OUT = Path(gettempdir()) / 'zsjos-approval-layout'
OUT.mkdir(exist_ok=True)
BASE = 'http://127.0.0.1:5174/test/approval-center-layout.html'
with sync_playwright() as p:
    browser = p.chromium.launch(channel='chrome', headless=True)
    page = browser.new_page(viewport={'width': 1920, 'height': 1080})
    page.set_default_timeout(15000)
    errors=[]
    page.on('pageerror', lambda error: errors.append(str(error)))
    def open_page(query='', width=1920):
        page.set_viewport_size({'width':width,'height':1080})
        page.goto(BASE + '?' + query)
        if 'table' in query or width <= 768:
            if width <= 768: page.locator('.business-inbox-item').first.click()
            else: page.get_by_role('button',name='详细',exact=False).first.click()
        expect(page.locator('.bpm-unified-detail')).to_have_count(1)
        expect(page.get_by_text('申请材料已补充。',exact=True)).to_be_visible()
        return page.locator('.bpm-unified-detail')
    def actions(detail):
        if detail.evaluate("e => e.classList.contains('is-narrow')"):
            detail.get_by_role('button',name='处理审批',exact=True).click()
        return detail.locator('.bpm-approval-actions')
    for width in [1920,1440,1024,768,390]:
        detail=open_page('',width)
        expect(detail.locator('.ant-tabs')).to_have_count(0)
        expect(detail.locator('[data-history-task="t1"]')).to_have_count(1)
        expect(detail.get_by_text('加签意见',exact=False)).to_be_visible()
        expect(detail.get_by_text('补充流转记录',exact=True)).to_be_visible()
        action=actions(detail)
        expect(action.locator('textarea')).to_be_visible()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 2')
        page.screenshot(path=str(OUT / f'layout-{width}.png'),full_page=True)
        print('PASS layout',width,flush=True)
    detail=open_page()
    action=actions(detail)
    action.locator('textarea').fill('同意申请')
    page.locator('.business-inbox-item').nth(1).click()
    expect(page.locator('.ant-modal-confirm-title').filter(has_text='放弃未提交内容？')).to_be_visible()
    page.get_by_role('button',name='继续编辑',exact=True).click()
    expect(action.locator('textarea')).to_have_value('同意申请')
    detail.get_by_role('button',name='刷新流程',exact=True).click()
    expect(action.locator('textarea')).to_have_value('同意申请')
    action.get_by_role('button',name='通过',exact=False).click()
    page.get_by_role('button',name='继续编辑',exact=True).click()
    expect(action.locator('textarea')).to_have_value('同意申请')
    action.get_by_role('button',name='通过',exact=False).click()
    page.get_by_role('button',name='确认提交',exact=True).click()
    expect(page.get_by_text('本次操作已完成',exact=True)).to_be_visible()
    assert page.evaluate('approvalFixture.actions.length')==1
    page.get_by_role('button',name='下一条待办',exact=True).click()
    expect(page.locator('.bpm-unified-detail')).to_contain_text('第二条申请')
    print('PASS draft, refresh, confirm, one submit, retained result, next task',flush=True)
    for query in ['feedback','table','table&feedback','readonly','stale','recordFail','commentFail','sign','long&dark']:
        if 'recordFail' in query or 'commentFail' in query:
            page.goto(BASE+'?'+query)
            expect(page.get_by_text('流转记录加载失败' if 'recordFail' in query else '评论加载失败',exact=True)).to_be_visible()
        else:
            detail=open_page(query)
            if query in ['readonly','stale']:
                expect(detail.locator('.bpm-approval-actions')).to_have_count(0)
            elif query=='sign':
                action=actions(detail);action.locator('textarea').fill('同意');action.get_by_role('button',name='通过',exact=False).click()
                expect(page.get_by_text('该节点要求签名，请先完成签名',exact=True)).to_be_visible()
                assert page.evaluate('approvalFixture.actions.length')==0
        print('PASS scenario',query,flush=True)
    detail=open_page('rejectWrite')
    action=actions(detail); action.locator('textarea').fill('保留失败意见')
    action.get_by_role('button',name='拒绝',exact=False).click()
    page.get_by_role('button',name='确认提交',exact=True).click()
    expect(page.get_by_text('提交失败，请重试',exact=True)).to_be_visible()
    expect(action.locator('textarea')).to_have_value('保留失败意见')
    page.evaluate('approvalFixture.rejectWrite=false')
    expect(action.get_by_role('button',name='拒绝',exact=False)).to_be_enabled()
    action.get_by_role('button',name='拒绝',exact=False).click()
    page.get_by_role('button',name='确认提交',exact=True).click()
    expect(page.get_by_text('本次操作已完成',exact=True)).to_be_visible()
    print('PASS reject failure preserves input and retries',flush=True)
    detail=open_page('table',1440); action=actions(detail); action.locator('textarea').fill('抽屉草稿')
    page.locator('.ant-drawer-close').click()
    page.get_by_role('button',name='继续编辑',exact=True).click()
    expect(action.locator('textarea')).to_have_value('抽屉草稿')
    print('PASS drawer close guard',flush=True)
    detail=open_page()
    page.get_by_role('tab',name='已办任务',exact=False).click()
    expect(page.get_by_text('本任务处理结果',exact=True)).to_be_visible()
    expect(page.locator('.bpm-approval-actions')).to_have_count(0)
    page.get_by_role('tab',name='待办任务',exact=False).click()
    detail=page.locator('.bpm-unified-detail'); action=actions(detail)
    action.locator('textarea').fill('返回前草稿')
    page.evaluate('history.back()')
    page.get_by_role('button',name='继续编辑',exact=True).click()
    expect(action.locator('textarea')).to_have_value('返回前草稿')
    page.get_by_role('link',name='测试离开页面').click()
    page.get_by_role('button',name='继续编辑',exact=True).click()
    expect(action.locator('textarea')).to_have_value('返回前草稿')
    print('PASS done readonly, browser back, route link guards',flush=True)
    detail=open_page()
    detail.locator('.bpm-approval-comments textarea').fill('独立流程评论')
    page.locator('.business-inbox-item').nth(1).click()
    page.get_by_role('button',name='继续编辑',exact=True).click()
    expect(detail.locator('.bpm-approval-comments textarea')).to_have_value('独立流程评论')
    detail.get_by_role('button',name='发表',exact=False).click()
    expect(detail.locator('.bpm-approval-comments textarea')).to_have_value('')
    assert page.evaluate('approvalFixture.actions[0].taskId')=='t1'
    print('PASS comment draft and submission',flush=True)
    page.goto(BASE+'?legacy')
    expect(page.locator('.bpm-approval-actions > textarea')).to_have_count(0)
    page.get_by_role('button',name='通过',exact=False).click()
    dialog=page.get_by_role('dialog')
    dialog.locator('textarea').fill('原弹窗流程')
    dialog.locator('.ant-modal-footer .ant-btn-primary').click()
    page.wait_for_function('approvalFixture.actions.length === 1')
    assert page.evaluate('approvalFixture.actions[0].reason')=='原弹窗流程'
    print('PASS shared default modal mode',flush=True)
    detail=open_page('',390); action=actions(detail)
    action.locator('textarea').fill('移动审批')
    action.get_by_role('button',name='通过',exact=False).click()
    page.get_by_role('button',name='确认提交',exact=True).click()
    expect(page.get_by_text('本次操作已完成',exact=True)).to_be_visible()
    print('PASS mobile confirmation stacking',flush=True)
    detail=open_page(); action=actions(detail)
    action.locator('textarea').fill('缩放保留的审批意见')
    detail.locator('.bpm-approval-comments textarea').fill('缩放保留的评论')
    page.set_viewport_size({'width':390,'height':900})
    page.locator('.business-inbox-item').first.click()
    detail=page.locator('.bpm-unified-detail'); action=actions(detail)
    expect(action.locator('textarea')).to_have_value('缩放保留的审批意见')
    expect(detail.locator('.bpm-approval-comments textarea')).to_have_value('缩放保留的评论')
    page.set_viewport_size({'width':1440,'height':1000})
    expect(page.locator('.bpm-unified-detail')).to_have_count(1)
    expect(action.locator('textarea')).to_have_value('缩放保留的审批意见')
    print('PASS responsive remount preserves memory drafts',flush=True)
    page.goto(BASE+'?slow')
    page.locator('.business-inbox-item').nth(1).click()
    expect(page.locator('.bpm-unified-detail')).to_contain_text('第二条申请')
    expect(page.locator('[data-history-task="t2"]')).to_have_count(1)
    expect(page.locator('[data-history-task="t1"]')).to_have_count(0)
    print('PASS slow old-task response cannot replace selected task',flush=True)
    for flag, title in [('recordFail','流转记录加载失败'),('commentFail','评论加载失败'),('fail','业务详情未完整加载')]:
        page.goto(BASE+'?'+flag)
        alert=page.locator('.ant-alert').filter(has_text=title)
        expect(alert).to_be_visible()
        page.evaluate('(key) => approvalFixture[key] = false', flag)
        alert.locator('button').click()
        expect(alert).to_have_count(0)
    print('PASS independent resource retries',flush=True)
    assert not errors,errors
    browser.close()

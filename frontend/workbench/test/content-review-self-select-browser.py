# -*- coding: utf-8 -*-
import os,json
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
base=os.environ.get('CONTENT_REVIEW_TEST_URL','http://127.0.0.1:5267/test/content-review-self-select.html')
out=Path(os.environ['TEMP'])/'content-review-self-select-browser';out.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True)
    for width in (1440,390):
        page=browser.new_page(viewport={'width':width,'height':960})
        page.goto(base)
        expect(page.get_by_text('仅本轮相关资料',exact=True)).to_be_visible()
        expect(page.get_by_role('button',name='编辑',exact=True)).to_have_count(0)
        expect(page.locator('.lead-detail-hero')).to_be_visible()
        expect(page.locator('.account-profile-aside')).to_be_visible()
        expect(page.locator('[data-profile-section="STATUS"]')).to_be_visible()
        expect(page.get_by_role('button',name='维护账号表')).to_have_count(0)
        page.get_by_role('button',name='查看定位访谈及附件').click()
        expect(page.get_by_role('dialog',name='查看定位访谈')).to_be_visible()
        expect(page.locator('textarea').filter(has_text='已核对访谈资料')).to_have_count(1)
        expect(page.get_by_role('button',name='保存草稿')).to_have_count(0)
        expect(page.locator('.attachment-card')).to_be_visible()
        page.wait_for_function('window.reviewFixture.requests.some(r=>r.url.endsWith("/file-content"))')
        page.locator('.ant-modal-footer button').click()
        page.get_by_role('tab',name='概览',exact=True).click()
        expect(page.locator('.student-overview-grid')).to_be_visible()
        expect(page.get_by_text('本次账号内容定位',exact=True).first).to_be_visible()
        page.get_by_role('tab',name='本轮账号 · 测试平台').click()
        page.screenshot(path=str(out/f'detail-{width}.png'),full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 2')
        page.get_by_role('button',name='提交测试审批').click()
        expect(page.get_by_role('dialog')).to_be_visible()
        page.get_by_role('combobox',name='本次审核编导').click()
        page.get_by_title('审核编导乙',exact=True).click()
        page.screenshot(path=str(out/f'select-{width}.png'),full_page=True)
        page.get_by_role('button',name='确认并提交').click()
        expect(page.get_by_text('提交成功',exact=True)).to_be_visible()
        sent=page.evaluate('window.reviewFixture.requests.filter(r=>r.url.endsWith("/submit"))')
        assert len(sent)==1 and json.loads(sent[0]['data'])=={'expectedVersion':2,'directorUserId':21,'processDefinitionId':'version-2'}
        page.evaluate('window.reviewFixture.expire()')
        page.get_by_role('button',name='刷新资料').click()
        expect(page.get_by_text('本次审批的学员查看权限已失效',exact=True)).to_be_visible()
        expect(page.get_by_text('已核对访谈资料',exact=True)).to_have_count(0)
        page.close()
    page=browser.new_page()
    page.goto(base+'?mode=revision');page.get_by_role('button',name='提交测试审批').click()
    expect(page.get_by_role('dialog').get_by_text('审核编导甲',exact=True)).to_be_visible()
    page.get_by_role('button',name='暂不提交').click()
    assert not page.evaluate('window.reviewFixture.requests.some(r=>r.url.endsWith("/submit"))')
    page.goto(base+'?mode=empty');page.get_by_role('button',name='提交测试审批').click()
    expect(page.get_by_text('当前没有可选编导',exact=True)).to_be_visible()
    page.get_by_role('button',name='确认并提交').click()
    assert not page.evaluate('window.reviewFixture.requests.some(r=>r.url.endsWith("/submit"))')
    page.goto(base+'?mode=tampered')
    expect(page.get_by_text('该账号不在本次审批范围内，请从审批详情重新进入',exact=True)).to_be_visible()
    assert not page.evaluate('window.reviewFixture.requests.some(r=>r.url.endsWith("/profile"))')
    page.goto(base+'?mode=ordinary')
    expect(page.locator('.account-profile-aside')).to_be_visible()
    expect(page.get_by_text('仅本轮相关资料',exact=True)).to_be_visible()
    assert page.evaluate('window.reviewFixture.requests.some(r=>r.url === "/zsjos/media-account/40/profile")')
    assert not page.evaluate('window.reviewFixture.requests.some(r=>r.url.includes("student-read"))')
    browser.close()
print('PASS desktop/mobile selection, resubmit confirmation, cancellation, empty candidates, read expiry, tampered account')

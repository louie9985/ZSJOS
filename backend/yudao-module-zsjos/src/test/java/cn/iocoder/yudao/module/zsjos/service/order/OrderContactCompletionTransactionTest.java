package cn.iocoder.yudao.module.zsjos.service.order;

import cn.iocoder.yudao.framework.tenant.core.context.TenantContextHolder;
import cn.iocoder.yudao.module.zsjos.dal.dataobject.lead.*;
import cn.iocoder.yudao.module.zsjos.dal.dataobject.event.BusinessEventDO;
import cn.iocoder.yudao.module.zsjos.dal.dataobject.order.SalesOrderDO;
import cn.iocoder.yudao.module.zsjos.dal.mysql.lead.*;
import cn.iocoder.yudao.module.zsjos.dal.mysql.event.BusinessEventMapper;
import cn.iocoder.yudao.module.zsjos.service.lead.PersonIdentityWriteService;
import org.junit.jupiter.api.*;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.*;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.annotation.AnnotationTransactionAttributeSource;
import org.springframework.transaction.interceptor.TransactionInterceptor;
import org.springframework.transaction.support.TransactionTemplate;
import java.util.UUID;
import java.util.concurrent.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;
import static org.mockito.ArgumentMatchers.*;

/** Real Spring transaction and row locks, with mapper/identity adapters writing isolated H2 tables. */
class OrderContactCompletionTransactionTest {
    JdbcTemplate jdbc;
    TransactionTemplate tx;
    OrderContactCompletionService service;
    @BeforeEach void setup() {
        TenantContextHolder.setTenantId(1L);
        var ds=new DriverManagerDataSource("jdbc:h2:mem:contacts_"+UUID.randomUUID()+";DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=10000","sa","");
        jdbc=new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE person(id BIGINT PRIMARY KEY, mobile VARCHAR(32), wechat VARCHAR(64))");
        jdbc.execute("CREATE TABLE lead(id BIGINT PRIMARY KEY, wechat VARCHAR(64))");
        jdbc.execute("CREATE TABLE orders(id BIGINT PRIMARY KEY)");
        jdbc.execute("CREATE TABLE events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
        jdbc.update("INSERT INTO person VALUES(10,'13800138000',NULL)");jdbc.update("INSERT INTO lead VALUES(20,NULL)");
        var people=mock(PersonMapper.class);var leads=mock(LeadMapper.class);
        var writer=mock(PersonIdentityWriteService.class);var events=mock(BusinessEventMapper.class);
        when(people.selectByIdForUpdate(10L,1L)).thenAnswer(a->jdbc.queryForObject("SELECT * FROM person WHERE id=10 FOR UPDATE",(rs,n)->{
            var p=new PersonDO().setId(10L).setName("测试").setMobile(rs.getString("mobile")).setWechatId(rs.getString("wechat"));p.setTenantId(1L);return p;
        }));
        when(leads.selectByIdForUpdate(20L,1L)).thenAnswer(a->jdbc.queryForObject("SELECT * FROM lead WHERE id=20 FOR UPDATE",(rs,n)->{
            var l=new LeadDO();l.setId(20L);l.setTenantId(1L);l.setPersonId(10L);l.setSubmittedMobile("13800138000");l.setSubmittedWechatId(rs.getString("wechat"));return l;
        }));
        when(writer.update(eq(10L),anyString(),anyString(),anyString())).thenAnswer(a->{jdbc.update("UPDATE person SET wechat=? WHERE id=10",(String)a.getArgument(3));return null;});
        when(leads.updateById(any(LeadDO.class))).thenAnswer(a->jdbc.update("UPDATE lead SET wechat=? WHERE id=20",((LeadDO)a.getArgument(0)).getSubmittedWechatId()));
        when(events.insert(any(BusinessEventDO.class))).thenAnswer(a->jdbc.update("INSERT INTO events DEFAULT VALUES"));
        var raw=new OrderContactCompletionService();
        ReflectionTestUtils.setField(raw,"personMapper",people);ReflectionTestUtils.setField(raw,"leadMapper",leads);
        ReflectionTestUtils.setField(raw,"identityWriter",writer);ReflectionTestUtils.setField(raw,"eventMapper",events);
        var manager=new DataSourceTransactionManager(ds);tx=new TransactionTemplate(manager);
        var proxy=new ProxyFactory(raw);proxy.setProxyTargetClass(true);
        proxy.addAdvice(new TransactionInterceptor(manager,new AnnotationTransactionAttributeSource()));
        service=(OrderContactCompletionService)proxy.getProxy();
    }
    @AfterEach void cleanup() {TenantContextHolder.clear();jdbc.execute("SHUTDOWN");}
    SalesOrderDO order(long id,String wechat) {var o=new SalesOrderDO();o.setId(id);o.setPersonId(10L);o.setStudentMobile("13800138000");o.setStudentWechatId(wechat);return o;}
    void submit(long id,Long leadId,boolean fail) {
        tx.executeWithoutResult(s->{jdbc.update("INSERT INTO orders VALUES(?)",id);service.complete(order(id,"new-wx"),leadId,99L);if(fail)throw new IllegalStateException("approval failed");});
    }
    @Test void approvalFailureRollsBackOrderPersonLeadAndAudit() {
        assertThrows(IllegalStateException.class,()->submit(30L,20L,true));
        assertNull(jdbc.queryForObject("SELECT wechat FROM person",String.class));assertNull(jdbc.queryForObject("SELECT wechat FROM lead",String.class));
        assertEquals(0,jdbc.queryForObject("SELECT COUNT(*) FROM orders",Integer.class));assertEquals(0,jdbc.queryForObject("SELECT COUNT(*) FROM events",Integer.class));
    }
    @Test void successCommitsAllAndRequiresCallerTransaction() {
        assertThrows(RuntimeException.class,()->service.complete(order(30L,"wx"),20L,99L));
        submit(30L,20L,false);assertEquals("new-wx",jdbc.queryForObject("SELECT wechat FROM person",String.class));
        assertEquals("new-wx",jdbc.queryForObject("SELECT wechat FROM lead",String.class));assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM events",Integer.class));
    }
    @Test void concurrentOrdersCannotOverwriteCompletedContact() throws Exception {
        var firstFilled=new CountDownLatch(1);var release=new CountDownLatch(1);
        try(var pool=Executors.newFixedThreadPool(2)) {
            var first=pool.submit(()->{TenantContextHolder.setTenantId(1L);try {tx.executeWithoutResult(s->{
                service.complete(order(30L,"first-wx"),null,99L);firstFilled.countDown();
                try {if(!release.await(10,TimeUnit.SECONDS))throw new IllegalStateException("timeout");} catch(InterruptedException e){throw new RuntimeException(e);}
            });}finally{TenantContextHolder.clear();}});
            assertTrue(firstFilled.await(10,TimeUnit.SECONDS));
            var second=pool.submit(()->{TenantContextHolder.setTenantId(1L);try{tx.executeWithoutResult(s->service.complete(order(31L,"second-wx"),null,98L));}finally{TenantContextHolder.clear();}});
            release.countDown();first.get(10,TimeUnit.SECONDS);second.get(10,TimeUnit.SECONDS);
            assertEquals("first-wx",jdbc.queryForObject("SELECT wechat FROM person",String.class));assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM events",Integer.class));
        } finally {release.countDown();}
    }
}

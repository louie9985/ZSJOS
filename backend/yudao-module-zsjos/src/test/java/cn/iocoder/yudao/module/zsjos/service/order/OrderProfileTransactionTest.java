import org.mockito.MockedStatic;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.*;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.annotation.AnnotationTransactionAttributeSource;
import org.springframework.transaction.interceptor.TransactionInterceptor;
import org.springframework.transaction.support.TransactionTemplate;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

/** Isolated H2 transaction evidence; not a substitute for live MySQL/API acceptance. */
class OrderProfileTransactionTest {
    JdbcTemplate jdbc; TransactionTemplate tx; OrderProfileService service; OrderProfileUpdateReqVO choice;
    MockedStatic<EncryptTypeHandler> crypto;
    @BeforeEach void setup() {
        TenantContextHolder.setTenantId(1L);
        var ds=new DriverManagerDataSource("jdbc:h2:mem:profile_"+UUID.randomUUID()+";DB_CLOSE_DELAY=-1","sa","");
        jdbc=new JdbcTemplate(ds);tx=new TransactionTemplate(new DataSourceTransactionManager(ds));
        jdbc.execute("CREATE TABLE person(id BIGINT PRIMARY KEY, name VARCHAR(100), mobile VARCHAR(32), wechat VARCHAR(64))");
        jdbc.execute("CREATE TABLE orders(id BIGINT PRIMARY KEY)");jdbc.execute("CREATE TABLE events(id BIGINT GENERATED BY DEFAULT AS IDENTITY)");
        jdbc.update("INSERT INTO person VALUES(10,'old','13800000001','old-demo')");
        var mapper=mock(PersonMapper.class);var writer=mock(PersonIdentityWriteService.class);var events=mock(BusinessEventMapper.class);
        when(mapper.selectByIdForUpdate(10L,1L)).thenAnswer(a->current());
        when(writer.update(eq(10L),anyString(),anyString(),anyString())).thenAnswer(a->{jdbc.update("UPDATE person SET name=?,mobile=?,wechat=? WHERE id=10",a.getArgument(1),a.getArgument(2),a.getArgument(3));return null;});
        when(events.insert(any(BusinessEventDO.class))).thenAnswer(a->jdbc.update("INSERT INTO events DEFAULT VALUES"));
        var raw=new OrderProfileService();ReflectionTestUtils.setField(raw,"personMapper",mapper);ReflectionTestUtils.setField(raw,"identityWriter",writer);ReflectionTestUtils.setField(raw,"eventMapper",events);
        var proxy=new ProxyFactory(raw);proxy.setProxyTargetClass(true);proxy.addAdvice(new TransactionInterceptor(new DataSourceTransactionManager(ds),new AnnotationTransactionAttributeSource()));
        service=(OrderProfileService)proxy.getProxy();
        choice=new OrderProfileUpdateReqVO();choice.setFingerprint(OrderProfileService.snapshot(current()).getFingerprint());choice.setFields(List.of("name","mobile","wechatId"));
        crypto=mockStatic(EncryptTypeHandler.class);crypto.when(()->EncryptTypeHandler.encrypt(anyString())).thenReturn("encrypted");
    }
    PersonDO current(){return jdbc.queryForObject("SELECT * FROM person WHERE id=10 FOR UPDATE",(rs,n)->{var p=new PersonDO().setId(10L).setName(rs.getString("name")).setMobile(rs.getString("mobile")).setWechatId(rs.getString("wechat"));p.setTenantId(1L);return p;});}
    SalesOrderDO order(){var o=new SalesOrderDO();o.setId(30L);o.setPersonId(10L);o.setStudentName("new");o.setStudentMobile("13800000002");o.setStudentWechatId("new-demo");return o;}
    @AfterEach void cleanup(){crypto.close();TenantContextHolder.clear();jdbc.execute("SHUTDOWN");}
    @Test void downstreamFailureRollsBackOrderIdentityAndAudit(){
        assertThrows(IllegalStateException.class,()->tx.executeWithoutResult(s->{jdbc.update("INSERT INTO orders VALUES(30)");service.apply(order(),choice,99L);throw new IllegalStateException("approval unavailable");}));
        assertEquals("old",current().getName());assertEquals("13800000001",current().getMobile());
        assertEquals(0,jdbc.queryForObject("SELECT COUNT(*) FROM orders",Integer.class));assertEquals(0,jdbc.queryForObject("SELECT COUNT(*) FROM events",Integer.class));
    }
    @Test void successfulUpdateMakesOldConfirmationStale(){
        tx.executeWithoutResult(s->service.apply(order(),choice,99L));
        assertEquals("new",current().getName());assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM events",Integer.class));
        assertThrows(RuntimeException.class,()->tx.executeWithoutResult(s->service.apply(order(),choice,99L)));
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM events",Integer.class));
    }
    @Test void callerTransactionIsRequired(){assertThrows(RuntimeException.class,()->service.apply(order(),choice,99L));}
}

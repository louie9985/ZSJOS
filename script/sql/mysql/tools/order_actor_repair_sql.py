    s+=fail("EXISTS(SELECT 1 FROM v312_images i WHERE (SELECT COUNT(*) FROM zsjos_data_repair_backup b WHERE b.repair_key='order-actors-v312' AND b.table_name=i.table_name AND b.row_id=i.row_id) NOT IN (0,2))", 'V312 incomplete evidence')

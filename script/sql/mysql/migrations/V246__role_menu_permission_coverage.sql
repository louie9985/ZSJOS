-- V246: ZSJ-OS 全角色工作台菜单权限配置
--
-- 目的
--   把当前已落地的 ZSJOS 工作台页面/按钮菜单，按各角色职责配置到 tenant 1 的 34 个稳定角色，
--   补齐 61 个此前无任何角色授权的 ZSJOS 权限菜单（素材库、内容审核、内容生产、礼品配置、
--   礼品采购、支付主体、学员信息收集表、销售反馈、个人日历、考期/课程日历、H5排行榜配置等）。
--
-- 范围说明
--   兼职端(part_time_partner)不在本迁移范围内: 兼职使用独立账号体系(zsjos_partner_account)
--   与独立令牌身份(UserTypeEnum.PARTNER)，不通过 System 角色消费菜单授权。其同名 System
--   角色由 V247 退役。
--
-- 口径来源
--   docs/architecture/zsjos-role-permission-matrix.md
--   docs/architecture/data-and-permission-flow.md
--   docs/frontend/zsjos-menu-coverage.md
--   各业务 handoff（main-content-review-refactor / main-materials / gift-feature-main 等）
--
-- 授权方式
--   目标菜单在生成时按 system_menu.permission 稳定标识解析得到，不按角色显示名、岗位名、
--   部门名或菜单 ID 授权（AGENTS.md 可配置权限契约）。每个角色的祖先目录单独补齐，
--   不存在跨角色共享目录被误授的问题。
--
-- 增量语义
--   只新增缺失关系，不撤销任何既有授权。既有越权项（sales 角色持有 query-all、
--   system_administrator 持有财务审核与资金导出等）属于独立问题，由文末只读核对 C2 报告，
--   不在本迁移中静默删除。
--
-- 可重复性
--   全部为 INSERT ... SELECT ... WHERE NOT EXISTS 语义；重复执行不产生重复关系。
--
-- 依赖与顺序
--   需先应用至 V245。必须在 backend 部署前或同批次应用，因为工作台路由依赖这些菜单授权。
--
-- 回滚限制
--   本迁移不提供自动回滚。回滚需精确删除 creator='V246' 的 system_role_menu 行；
--   禁止按 menu_id 范围批量删除，以免影响其他来源的授权。
--
-- 编码
--   源文件与客户端连接均为 utf8mb4；仅写入 ASCII 权限标识、角色编码与菜单 ID，不含中文业务数据。


          'zsjos:sales-order:review','zsjos:cashback:finance-query',
          'zsjos:withdrawal:finance-query','zsjos:withdrawal:review','zsjos:withdrawal:payout',
          'zsjos:export:order','zsjos:export:finance-order','zsjos:export:cashback',
          'zsjos:export:withdrawal'))
  )
ORDER BY r.code, m.permission;

-- C3) 各角色 ZSJOS 权限菜单数量概览。
SELECT 'C3-count' AS check_name, r.code AS role_code, r.name AS role_name,
       COUNT(DISTINCT m.id) AS zsjos_menu_count

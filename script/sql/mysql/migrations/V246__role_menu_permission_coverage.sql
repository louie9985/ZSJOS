LEFT JOIN `system_menu` m ON m.id=rm.menu_id AND m.deleted=b'0' AND m.permission LIKE 'zsjos:%'
WHERE r.deleted=b'0' AND r.tenant_id=1
GROUP BY r.id, r.code, r.name
ORDER BY zsjos_menu_count DESC, r.id;

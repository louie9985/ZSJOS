--   524(汪雅琪2) 无客资归属，本迁移停用；它作为**提交人**出现在 4 条客资上
--   (`source_user_id`)，那是提交事实而非归属，保持不动。
--
-- 目标态（对齐新库现有教务自拓客资 id=6491 的形状）
--   zsjos_lead: owner_user_id / owner_identity='education' / assignment_status='owned'
--               / ownership_started_at / current_assignment_history_id
--   zsjos_lead_assignment_history: 一条 action_type='accept' 的归属轮次
--   zsjos_lead_follow_up_record: 每条跟进必须带 assignment_history_id 与
--               owner_user_id_snapshot / owner_identity_snapshot
--               （列均 NOT NULL，见 zsjos_db schema_drift 约束）
--
-- 明确不做
--   - 不改客资业务状态、金额、订单、意向产品
--   - 不动已归属客资（当前有 5 条挂在销售 60/61 名下，与旧库 owner 不一致，

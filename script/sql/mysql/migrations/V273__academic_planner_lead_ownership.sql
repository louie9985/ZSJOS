--   合并时客资与跟进记录的主体随 person/lead 进了新库，但：
--     1) 归属字段没写 —— 177 条里 172 条 owner_user_id/owner_identity 为空，
--        规划师登录后看不到自己的客资（即「学习规划师客资数据缺失」）。
--     2) 141 条跟进记录从未迁移。
--
--   新库没有 academic 对应表，这批客资就是普通 `zsjos_lead` 行，靠
--   `zsjos_person.person_no` 的导入标记回溯旧 lead：存在两种前缀
--   `LEGACY-P-<旧lead_id>` 与 `LEGACY-PERSON-<旧lead_id>`（两次导入批次不同）。
--   本迁移不依赖旧库连接：177 条「新 lead_id -> 旧 owner_id」对照与 141 条
--   跟进明细都以显式数据块写死，可逐行审计（见分节 2 与 3 的数据块）。
--
-- 账号映射（业务确认，非姓名/手机号推断）
--   旧 employees_employee_profile.id -> 新 system_users.id

#!/usr/bin/env python3
"""Fill submitted_at from the legacy registration task's creation time.

The legacy submission moment lives in `orders_registration_task.created_at`:
that row is created the instant an order enters approval. It was verified to
agree with the migrated `create_time` for all 60 affected orders -- 58 exactly,
the remaining 2 within the one-second rounding the import applied -- which
confirms the two denote the same event.

The written value is therefore `create_time` itself, not a re-derived
timestamp. Native orders hold `submitted_at = create_time` to the second, so
reusing the migrated value keeps these orders under that same convention
instead of introducing a second, subtly different timeline.

Rows are joined by order number -> legacy order id, never by a cached id list.

Usage: generate_submitted_at_sql.py <schema> <out.sql>
"""
import sys
from collections import Counter

sys.path.insert(0, '/tmp')
from legacy_tables import load as load_table
from legacy_parse import load as load_orders

SCHEMA = sys.argv[1] if len(sys.argv) > 1 else 'zsjos'
OUT = sys.argv[2] if len(sys.argv) > 2 else '/tmp/submitted_at.sql'
DUMP = '/tmp/pt_cst.sql'
ORDER = f"{SCHEMA}.zsjos_order"

legacy_orders = load_orders(DUMP)
by_order_no = {r['order_no']: r for r in legacy_orders.values()}

tasks = load_table(DUMP, 'orders_registration_task',
                   ['id', 'status', 'is_proxy', 'result_reason', 'started_at', 'completed_at',
                    'created_at', 'updated_at', 'current_handler_id', 'default_owner_id',
                    'final_reviewer_id', 'order_id'])
task_by_legacy_order = {}
for t in tasks:
    if t['order_id'] in ('NULL', None, ''):
        continue
    task_by_legacy_order[int(t['order_id'])] = t

rows = []
with open('/tmp/gap2.tsv', encoding='utf8') as fh:
    for line in fh:
        f = line.rstrip('\n').split('\t')
        if len(f) < 7:
            continue
        order_no, status, lid = f[0], f[2], f[5]

        src = by_order_no.get(order_no)
        if src is None:
            raise SystemExit(f"{order_no}: no legacy order row")
        # Guard against a stale id: the export and the dump must agree.
        if str(src['id']) != lid:
            raise SystemExit(f"{order_no}: legacy id mismatch export={lid} dump={src['id']}")
        task = task_by_legacy_order.get(src['id'])
        if task is None or not task['created_at']:
            raise SystemExit(f"{order_no}: no legacy registration task time")

        rows.append((order_no, status, f[3], task['created_at'], task['status']))

lines = [
    "-- submitted_at backfill -- generated by generate_submitted_at_sql.py.",
    "-- Source: legacy parttimecrm orders_registration_task.created_at, the moment",
    "-- the order entered approval. Verified to match the migrated create_time.",
    "-- Guarded on `submitted_at IS NULL`: re-running is a no-op.",
    "",
]
for order_no, status, value, task_created, task_status in rows:
    lines.append(f"-- {order_no} ({status}); legacy task {task_status} created {task_created[:19]}")
    lines.append(f"UPDATE {ORDER} o SET")
    lines.append(f"    o.submitted_at = '{value}'")
    lines.append(f"WHERE o.tenant_id = @TENANT_ID")
    lines.append(f"  AND o.deleted = b'0'")
    lines.append(f"  AND o.order_no = '{order_no}'")
    lines.append(f"  AND o.submitted_at IS NULL;")
    lines.append("")

with open(OUT, 'w', encoding='utf8') as fh:
    fh.write('\n'.join(lines))

print(f"wrote {OUT}")
print(f"  statements: {len(rows)}")
for k, v in Counter(r[1] for r in rows).most_common():
    print(f"    {k}: {v}")

#!/usr/bin/env python3
"""Emit one merged repair script covering both plans.

Plan 1 (/tmp/repair_plan.tsv)       -- legacy revision-chain rebuild
Plan 2 (/tmp/effective_at_plan.tsv) -- effective_at for orders that never got one

Each field is written by its own statement, guarded only on the value that
statement changes. Bundling several fields into one UPDATE forces their guards
to be ANDed together, and a guard on a value the order already has then
silently suppresses every sibling change in that statement.

Usage: generate_merged_sql.py <schema> <out.sql>
"""
import sys
from collections import OrderedDict, Counter

SCHEMA = sys.argv[1] if len(sys.argv) > 1 else 'zsjos'
OUT = sys.argv[2] if len(sys.argv) > 2 else '/tmp/merged.sql'
ORDER = f"{SCHEMA}.zsjos_order"

chain = OrderedDict()                      # order_no -> {field: value}
for line in open('/tmp/repair_plan.tsv', encoding='utf8'):
    f = line.rstrip('\n').split('\t')
    if len(f) < 7 or f[0] == 'order_no':
        continue
    chain.setdefault(f[0], {})[f[3]] = f[5]

backfill = OrderedDict()                   # order_no -> (effective_at, source)
for line in open('/tmp/effective_at_plan.tsv', encoding='utf8'):
    f = line.rstrip('\n').split('\t')
    if len(f) < 4 or f[0] == 'order_no':
        continue
    backfill[f[0]] = (f[2], f[3])

lines = [
    "-- Merged order-history repair -- generated by generate_merged_sql.py.",
    "-- Plan 1: legacy revision chain (status / supersede link / pointer / effective_at).",
    "-- Plan 2: effective_at for orders that never received one.",
    "-- One statement per field; each is guarded on its own pre-repair value,",
    "-- so re-running the whole script is a no-op.",
    "",
    "-- MySQL cannot read the UPDATE target inside a subquery, so the",
    "-- order_no -> id map is materialised once and joined instead.",
    f"DROP TEMPORARY TABLE IF EXISTS {SCHEMA}.tmp_successor_ids;",
    f"CREATE TEMPORARY TABLE {SCHEMA}.tmp_successor_ids AS",
    f"SELECT order_no, id AS order_id FROM {ORDER}",
    f"WHERE tenant_id = @TENANT_ID AND deleted = b'0';",
    f"ALTER TABLE {SCHEMA}.tmp_successor_ids ADD PRIMARY KEY (order_no);",
    "",
]

counts = Counter()


def base_guards(order_no):
    return ["o.tenant_id = @TENANT_ID", "o.deleted = b'0'", f"o.order_no = '{order_no}'"]


def emit(sets, guards, comment):
    counts[comment] += 1
    lines.append(f"-- {comment}")
    lines.append(f"UPDATE {ORDER} o SET")
    lines.append(",\n".join(sets))
    lines.append("WHERE " + "\n  AND ".join(guards) + ";")
    lines.append("")


lines.append("-- ===== plan 1: legacy revision chain =====")
for order_no, fields in sorted(chain.items()):
    if 'status' in fields:
        emit([f"    o.status = '{fields['status']}'"],
             base_guards(order_no) + [f"o.status <> '{fields['status']}'"],
             f"status {order_no} -> {fields['status']}")
    if 'effective_at' in fields:
        emit([f"    o.effective_at = '{fields['effective_at']}'"],
             base_guards(order_no) + ["o.effective_at IS NULL"],
             f"effective_at {order_no} = {fields['effective_at']}")
    if 'superseded_by' in fields:
        emit([f"    o.superseded_by_order_id = (\n"
              f"        SELECT t.order_id FROM {SCHEMA}.tmp_successor_ids t\n"
              f"        WHERE t.order_no = '{fields['superseded_by']}')"],
             base_guards(order_no) + ["o.superseded_by_order_id IS NULL"],
             f"superseded_by {order_no} -> {fields['superseded_by']}")
    if 'current_approval_round_id' in fields:
        emit([f"    o.current_approval_round_id = {fields['current_approval_round_id']}"],
             base_guards(order_no) + ["o.current_approval_round_id IS NULL"],
             f"pointer {order_no} = {fields['current_approval_round_id']}")

lines.append("-- ===== plan 2: effective_at backfill =====")
for order_no, (value, source) in sorted(backfill.items()):
    if order_no in chain and 'effective_at' in chain[order_no]:
        continue                            # plan 1 owns this value
    emit([f"    o.effective_at = '{value}'"],
         base_guards(order_no) + ["o.effective_at IS NULL"],
         f"effective_at {order_no} = {value}  ({source})")

lines.append(f"DROP TEMPORARY TABLE IF EXISTS {SCHEMA}.tmp_successor_ids;")

with open(OUT, 'w', encoding='utf8') as fh:
    fh.write('\n'.join(lines))

print(f"wrote {OUT}")
print(f"  statements: {sum(counts.values())}")
for field in ('status', 'effective_at', 'superseded_by', 'pointer'):
    print(f"    {field}: {sum(v for k, v in counts.items() if k.startswith(field))}")

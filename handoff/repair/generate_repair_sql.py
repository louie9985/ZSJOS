#!/usr/bin/env python3
"""Generate the per-order repair statements for the legacy chain rebuild.

Reads the plan produced by build_plan.py and emits guarded, idempotent SQL.
Every statement carries a status/pointer guard so a repeated run is a no-op.

Usage:
    generate_repair_sql.py /tmp/repair_plan.tsv /tmp/plan_statements.sql [schema]

`schema` qualifies every table reference so the script can be applied to a
scratch copy without relying on a USE statement. It defaults to `zsjos`.
"""
import sys
from collections import defaultdict

plan_path = sys.argv[1] if len(sys.argv) > 1 else '/tmp/repair_plan.tsv'
out_path = sys.argv[2] if len(sys.argv) > 2 else '/tmp/plan_statements.sql'
SCHEMA = sys.argv[3] if len(sys.argv) > 3 else 'zsjos'

ORDER = f"{SCHEMA}.zsjos_order"

# order_no -> {field: new}
by_order = defaultdict(dict)
meta = {}
with open(plan_path, encoding='utf8') as fh:
    next(fh)
    for line in fh:
        f = line.rstrip('\n').split('\t')
        if len(f) < 7:
            continue
        order_no, order_id, legacy_id, field, old, new, note = f[:7]
        by_order[order_no][field] = new
        meta[order_no] = (int(order_id), int(legacy_id), note)

lines = []
lines.append("-- Generated by generate_repair_sql.py -- do not edit by hand.")
lines.append("-- One statement per order; guarded so re-running is a no-op.")
lines.append("")
lines.append("-- MySQL forbids reading the UPDATE target inside a subquery (error 1093),")
lines.append("-- so the order_no -> id map is materialised once and joined instead.")
lines.append(f"DROP TEMPORARY TABLE IF EXISTS {SCHEMA}.tmp_successor_ids;")
lines.append(f"CREATE TEMPORARY TABLE {SCHEMA}.tmp_successor_ids AS")
lines.append(f"SELECT order_no, id AS order_id FROM {ORDER}")
lines.append(f"WHERE tenant_id = @TENANT_ID AND deleted = b'0';")
lines.append(f"ALTER TABLE {SCHEMA}.tmp_successor_ids ADD PRIMARY KEY (order_no);")
lines.append("")

for order_no in sorted(by_order):
    fields = by_order[order_no]
    order_id, legacy_id, note = meta[order_no]
    sets = []

    if 'status' in fields:
        sets.append(f"    o.status = '{fields['status']}'")
    if 'effective_at' in fields:
        sets.append(f"    o.effective_at = '{fields['effective_at']}'")
    if 'superseded_by' in fields:
        sets.append(
            "    o.superseded_by_order_id = (\n"
            f"        SELECT t.order_id FROM {SCHEMA}.tmp_successor_ids t\n"
            f"        WHERE t.order_no = '{fields['superseded_by']}')"
        )
    if 'current_approval_round_id' in fields:
        sets.append(f"    o.current_approval_round_id = {fields['current_approval_round_id']}")

    if not sets:
        continue

    # Guard: only touch rows still in the pre-repair state.
    # Each guard must be independently meaningful: combining a "still NULL" test
    # with a pointer test can never match once the pointer backfill has run.
    guards = ["o.tenant_id = @TENANT_ID", "o.deleted = b'0'",
              f"o.order_no = '{order_no}'"]
    if 'status' in fields:
        guards.append(f"o.status <> '{fields['status']}'")
    if 'effective_at' in fields:
        guards.append("o.effective_at IS NULL")
    if 'current_approval_round_id' in fields and 'status' not in fields and 'effective_at' not in fields:
        guards.append("o.current_approval_round_id IS NULL")

    lines.append(f"-- {order_no} (legacy {legacy_id}): {note}")
    lines.append(f"UPDATE {ORDER} o SET")
    lines.append(",\n".join(sets))
    lines.append("WHERE " + "\n  AND ".join(guards) + ";")
    lines.append("")

with open(out_path, 'w', encoding='utf8') as fh:
    fh.write('\n'.join(lines))

n_status = sum(1 for v in by_order.values() if 'status' in v)
n_link = sum(1 for v in by_order.values() if 'superseded_by' in v)
n_eff = sum(1 for v in by_order.values() if 'effective_at' in v)
print(f"statements for {len(by_order)} orders -> {out_path}")
print(f"  status changes: {n_status}, supersede links: {n_link}, effective_at: {n_eff}")
